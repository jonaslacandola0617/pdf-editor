test('bulk rotate, extract, delete and undo preserve real pages and rotations', async ({ page }, info) => {
  const path = info.outputPath('bulk.pdf')
  await source(path)
  await open(page, path)
  await page.getByLabel('Select page 1', { exact: true }).check()
  await page.getByLabel('Select page 3', { exact: true }).check()
  await page.getByTitle('Rotate selected right').click()
  const download = page.waitForEvent('download')
  await page.getByTitle('Extract selected pages').click()
  const extractPath = info.outputPath('selected.pdf')
  await (await download).saveAs(extractPath)
  const extracted = await PDFDocument.load(await readFile(extractPath))
  expect(extracted.getPageCount()).toBe(2)
  expect(extracted.getPages().map(p => p.getRotation().angle)).toEqual([90, 90])
  await page.getByTitle('Delete selected pages').click()
  await expect(page.locator('.stage-top-hint')).toContainText('Selected pages deleted')
  expect((await exported(page, info.outputPath('deleted.pdf'))).getPageCount()).toBe(1)
  await page.getByTitle('Undo', { exact: true }).click()
  const restored = await exported(page, info.outputPath('undo.pdf'))
  expect(restored.getPages().map(p => p.getRotation().angle)).toEqual([90, 0, 90])
  await page.getByTitle('Redo', { exact: true }).click()
  expect((await exported(page, info.outputPath('redo.pdf'))).getPageCount()).toBe(1)
  await page.getByLabel('Select page 1', { exact: true }).check()
  await page.getByTitle('Delete selected pages').click()
  await expect(page.locator('.stage-top-hint')).toContainText('at least one page')
  expect((await exported(page, info.outputPath('retained.pdf'))).getPageCount()).toBe(1)
})

