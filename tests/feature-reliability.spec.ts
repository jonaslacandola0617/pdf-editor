test('existing page rotations render and export without flattening document structure', async ({ page }, info) => {
  const pdf = await PDFDocument.create()
  const sheet = pdf.addPage([612, 792])
  sheet.setRotation(degrees(90))
  const form = pdf.getForm().createTextField('rotated_field')
  form.setText('kept'); form.addToPage(sheet, { x: 40, y: 60, width: 120, height: 24 })
  const path = info.outputPath('pre-rotated.pdf')
  await writeFile(path, await pdf.save())
  await open(page, path)
  const canvas = await page.locator('.pdf-page canvas').first().boundingBox()
  expect(canvas!.width).toBeGreaterThan(canvas!.height)
  const reopened = await exported(page, info.outputPath('pre-rotated-export.pdf'))
  expect(reopened.getPage(0).getRotation().angle).toBe(90)
  expect(reopened.getForm().getTextField('rotated_field').getText()).toBe('kept')
})

test('all fillable field types, clear values and rotation persist without losing AcroForms', async ({ page }, info) => {
  const pdf = await PDFDocument.create()
  const sheet = pdf.addPage([612, 792])
  const form = pdf.getForm()
  const text = form.createTextField('text')
  text.setText('Original'); text.addToPage(sheet, { x: 50, y: 680 })
  form.createCheckBox('check').addToPage(sheet, { x: 50, y: 620 })
  const dropdown = form.createDropdown('dropdown')
  dropdown.addOptions(['A', 'B']); dropdown.select('A'); dropdown.addToPage(sheet, { x: 50, y: 560 })
  const list = form.createOptionList('list')
  list.addOptions(['One', 'Two', 'Three']); list.enableMultiselect(); list.select(['One', 'Two']); list.addToPage(sheet, { x: 50, y: 420 })
  const radio = form.createRadioGroup('radio')
  radio.addOptionToPage('Yes', sheet, { x: 300, y: 620 }); radio.addOptionToPage('No', sheet, { x: 350, y: 620 }); radio.select('Yes')
  const locked = form.createTextField('locked')
  locked.setText('Read only'); locked.addToPage(sheet, { x: 50, y: 350 }); locked.enableReadOnly()
  const path = info.outputPath('all-fields.pdf')
  await writeFile(path, await pdf.save())
  await open(page, path)
  await page.getByTitle('Form fields', { exact: true }).click()
  const field = (name: string) => page.locator('.form-field').filter({ has: page.locator('span', { hasText: new RegExp(`^${name}$`) }) })
  await expect(field('locked').locator('input')).toBeDisabled()
  await expect(field('list').locator('select')).toHaveValues(['One', 'Two'])
  await field('text').locator('input').fill('Persisted value')
  await field('text').locator('input').press('Tab')
  await expect(page.locator('.stage-top-hint')).toContainText('Form field updated')
  await field('check').locator('input').check()
  await expect(field('check').locator('input')).toBeChecked()
  await field('list').locator('select').selectOption(['Two', 'Three'])
  await expect(field('list').locator('select')).toHaveValues(['Two', 'Three'])
  await field('dropdown').locator('select').selectOption('')
  await expect(field('dropdown').locator('select')).toHaveValue('')
  await field('radio').locator('select').selectOption('')
  await expect(field('radio').locator('select')).toHaveValue('')
  await page.getByTitle('Pages', { exact: true }).click()
  await page.getByTitle('Rotate right', { exact: true }).click()
  const reopened = await exported(page, info.outputPath('all-fields-export.pdf'))
  expect(reopened.getPage(0).getRotation().angle).toBe(90)
  const saved = reopened.getForm()
  expect(saved.getFields()).toHaveLength(6)
  expect(saved.getTextField('text').getText()).toBe('Persisted value')
  expect(saved.getCheckBox('check').isChecked()).toBe(true)
  expect(saved.getDropdown('dropdown').getSelected()).toEqual([])
  expect(saved.getOptionList('list').getSelected()).toEqual(['Two', 'Three'])
  expect(saved.getRadioGroup('radio').getSelected()).toBeUndefined()
  expect(saved.getTextField('locked').getText()).toBe('Read only')
})